def parse_array_data(data_str):
    start = data_str.find('{')
    end = data_str.rfind('}')
    content = data_str[start+1:end]
    inner_blocks = re.findall(r'\{([^}]+)\}', content)
    rows = []
    for block in inner_blocks:
        nums = [int(n.strip(), 0) for n in block.split(',')]
        rows.append(nums)
    return rows

